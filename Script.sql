CREATE OR REPLACE FUNCTION trg_doctor_count_fn() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' AND NEW.doctor_id IS NOT NULL THEN
        UPDATE doctors SET patient_count = patient_count + 1 WHERE id = NEW.doctor_id;
    ELSIF TG_OP = 'DELETE' AND OLD.doctor_id IS NOT NULL THEN
        UPDATE doctors SET patient_count = GREATEST(patient_count - 1, 0) WHERE id = OLD.doctor_id;
    ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.doctor_id IS DISTINCT FROM NEW.doctor_id THEN
            IF OLD.doctor_id IS NOT NULL THEN
                UPDATE doctors SET patient_count = GREATEST(patient_count - 1, 0) WHERE id = OLD.doctor_id;
            END IF;
            IF NEW.doctor_id IS NOT NULL THEN
                UPDATE doctors SET patient_count = patient_count + 1 WHERE id = NEW.doctor_id;
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_doctor_count
AFTER INSERT OR UPDATE OF doctor_id OR DELETE ON patients
FOR EACH ROW EXECUTE FUNCTION trg_doctor_count_fn();

CREATE OR REPLACE FUNCTION trg_patient_discharge_fn() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.discharge_status <> 'на лечении' AND NEW.discharge_date IS NULL THEN
        NEW.discharge_date := CURRENT_DATE;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_patient_discharge
BEFORE INSERT OR UPDATE ON patients
FOR EACH ROW EXECUTE FUNCTION trg_patient_discharge_fn();

CREATE OR REPLACE VIEW v_hospitals AS
SELECT id, name, address, phone
FROM hospitals
ORDER BY name;

CREATE OR REPLACE VIEW v_patient_card AS
SELECT
    p.id,
    h.name AS hospital,
    dp.name AS department,
    p.last_name || ' ' || p.first_name || ' ' || COALESCE(p.middle_name, '') AS patient_full,
    p.birth_date,
    DATE_PART('year', AGE(p.birth_date))::INTEGER AS age,
    p.insurance_num,
    p.admission_date,
    p.discharge_date,
    p.discharge_status,
    d.last_name || ' ' || d.first_name AS doctor,
    pos.title AS doctor_position,
    DATE_PART('year', AGE(d.hire_date))::INTEGER AS doctor_exp_years,
    dg.code || ' — ' || dg.name AS diagnosis
FROM patients p
JOIN hospitals h ON p.hospital_id = h.id
JOIN departments dp ON p.department_id = dp.id
LEFT JOIN doctors d ON p.doctor_id = d.id
LEFT JOIN positions pos ON d.position_id = pos.id
LEFT JOIN diagnoses dg ON p.diagnosis_id = dg.id;

CREATE OR REPLACE VIEW v_busy_departments AS
SELECT
    h.name AS hospital,
    dp.name AS department,
    COUNT(p.id) AS patient_count,
    COUNT(CASE WHEN p.discharge_date IS NULL THEN 1 END) AS active_count,
    ROUND(AVG(DATE_PART('year', AGE(p.birth_date)))::NUMERIC, 1) AS avg_age,
    ROUND(COUNT(p.id) * 100.0 / NULLIF(dp.bed_count, 0), 1) AS fill_pct
FROM departments dp
JOIN hospitals h ON dp.hospital_id = h.id
LEFT JOIN patients p ON p.department_id = dp.id
GROUP BY h.name, dp.name, dp.bed_count
HAVING COUNT(p.id) >= 2
ORDER BY patient_count DESC;

CREATE OR REPLACE VIEW v_doctor_workload AS
SELECT
    d.id,
    d.last_name || ' ' || d.first_name AS doctor,
    pos.title AS position,
    DATE_PART('year', AGE(d.hire_date))::INTEGER AS exp_years,
    h.name AS hospital,
    dp.name AS department,
    d.patient_count AS patients_now,
    COUNT(p.id) AS patients_total
FROM doctors d
LEFT JOIN patients p ON p.doctor_id = d.id
LEFT JOIN positions pos ON d.position_id = pos.id
LEFT JOIN hospitals h ON d.hospital_id = h.id
LEFT JOIN departments dp ON d.department_id = dp.id
GROUP BY d.id, pos.title, h.name, dp.name
ORDER BY patients_total DESC;

