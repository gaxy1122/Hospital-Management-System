CREATE TABLE hospitals (
    id          SERIAL        PRIMARY KEY,
    name        VARCHAR(200)  NOT NULL,
    address     VARCHAR(300),
    phone       VARCHAR(50)   DEFAULT 'не указан',
    CONSTRAINT chk_hosp_name CHECK (TRIM(name) <> '')
);

CREATE TABLE departments (
    id          SERIAL        PRIMARY KEY,
    hospital_id INTEGER       NOT NULL REFERENCES hospitals(id) ON DELETE CASCADE,
    name        VARCHAR(150)  NOT NULL,
    head_name   VARCHAR(150)  DEFAULT 'вакансия',
    floor       SMALLINT      DEFAULT 1,
    bed_count   SMALLINT      DEFAULT 0,
    CONSTRAINT chk_dept_name   CHECK (TRIM(name) <> ''),
    CONSTRAINT chk_dept_floor  CHECK (floor BETWEEN 1 AND 20),
    CONSTRAINT chk_dept_beds   CHECK (bed_count >= 0)
);

CREATE TABLE positions (
    id             SERIAL       PRIMARY KEY,
    title          VARCHAR(100) NOT NULL UNIQUE,
    work_experience NUMERIC(10,2) DEFAULT 0,
    CONSTRAINT chk_pos_title CHECK (TRIM(title) <> ''),
    CONSTRAINT chk_pos_exp CHECK (work_experience >= 0)
);

CREATE TABLE diagnoses (
    id          SERIAL       PRIMARY KEY,
    code        VARCHAR(10)  NOT NULL UNIQUE,
    name        VARCHAR(200) NOT NULL,
    treatment   TEXT         DEFAULT 'методика лечения не указана',
    severity    SMALLINT     DEFAULT 1,
    CONSTRAINT chk_diag_name CHECK (TRIM(name) <> ''),
    CONSTRAINT chk_diag_severity CHECK (severity BETWEEN 1 AND 5)
);

CREATE TABLE doctors (
    id            SERIAL       PRIMARY KEY,
    hospital_id   INTEGER      NOT NULL REFERENCES hospitals(id) ON DELETE CASCADE,
    department_id INTEGER      NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
    last_name     VARCHAR(80)  NOT NULL,
    first_name    VARCHAR(80)  NOT NULL,
    middle_name   VARCHAR(80),
    position_id   INTEGER      REFERENCES positions(id) ON DELETE SET NULL,
    cabinet       VARCHAR(10)  DEFAULT '-',
    hire_date     DATE         DEFAULT CURRENT_DATE,
    patient_count INTEGER      DEFAULT 0,
    CONSTRAINT chk_doc_name CHECK (TRIM(last_name) <> '' AND TRIM(first_name) <> '')
);

CREATE TABLE patients (
    id                SERIAL       PRIMARY KEY,
    hospital_id       INTEGER      NOT NULL REFERENCES hospitals(id) ON DELETE CASCADE,
    department_id     INTEGER      NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
    doctor_id         INTEGER      REFERENCES doctors(id) ON DELETE SET NULL,
    diagnosis_id      INTEGER      REFERENCES diagnoses(id) ON DELETE SET NULL,
    last_name         VARCHAR(80)  NOT NULL,
    first_name        VARCHAR(80)  NOT NULL,
    middle_name       VARCHAR(80),
    birth_date        DATE,
    insurance_num     VARCHAR(20)  UNIQUE,
    admission_date    DATE         NOT NULL DEFAULT CURRENT_DATE,
    discharge_date    DATE,
    discharge_status  VARCHAR(50)  DEFAULT 'на лечении',
    CONSTRAINT chk_pat_name CHECK (TRIM(last_name) <> '' AND TRIM(first_name) <> ''),
    CONSTRAINT chk_pat_birth CHECK (birth_date BETWEEN '1900-01-01' AND CURRENT_DATE),
    CONSTRAINT chk_pat_dates CHECK (discharge_date IS NULL OR discharge_date >= admission_date),
    CONSTRAINT chk_pat_status CHECK (discharge_status IN ('на лечении','выписан','переведён','умер'))
);

CREATE INDEX idx_dept_hospital ON departments(hospital_id);
CREATE INDEX idx_doc_hospital ON doctors(hospital_id);
CREATE INDEX idx_doc_department ON doctors(department_id);
CREATE INDEX idx_doc_position ON doctors(position_id);
